        private static final DateTimeFormatter FORMATO_DATA = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

    private final PedidoDAO pedidoDAO = new PedidoDAO();
    private DefaultTableModel modeloTabela;

    public TelaPedidos() {
        initComponents();
        setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        setLocationRelativeTo(null);

        String[] colunas = {"ID", "Cliente", "Data/Hora", "Forma Pagto.", "Status", "Total"};
        modeloTabela = new DefaultTableModel(colunas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabela.setModel(modeloTabela);
        tabela.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        carregarPedidos();
    }

    private void carregarPedidos() {
        try {
            modeloTabela.setRowCount(0);
            List<Pedido> pedidos = pedidoDAO.listarTodos();
            for (Pedido p : pedidos) {
                modeloTabela.addRow(new Object[]{
                    p.getId(),
                    p.getCliente().getNome(),
                    p.getDataHora().format(FORMATO_DATA),
                    p.getFormaPagamento(),
                    p.getStatus(),
                    "R$ " + p.getValorTotal()
                });
            }
        } catch (SQLException e) {
            exibirErroBanco(e);
        }
    }

    private Integer obterIdSelecionado() {
        int linha = tabela.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um pedido na tabela.",
                    "Atencao", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return (Integer) modeloTabela.getValueAt(linha, 0);
    }

    private void editarSelecionado() {
        Integer id = obterIdSelecionado();
        if (id != null) {
            abrirTelaPedido(id);
        }
    }

    private void abrirTelaPedido(Integer idPedido) {
        TelaPedido tela = new TelaPedido(this, idPedido);
        tela.setVisible(true);
    }

    private void excluirSelecionado() {
        Integer id = obterIdSelecionado();
        if (id == null) {
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Tem certeza que deseja excluir este pedido e todos os seus itens?",
                "Confirmar exclusao", JOptionPane.YES_NO_OPTION);
        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            pedidoDAO.excluir(id);
            JOptionPane.showMessageDialog(this, "Pedido excluido com sucesso!");
            carregarPedidos();
        } catch (SQLException e) {
            exibirErroBanco(e);
        }
    }

    private void exibirErroBanco(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao acessar o banco de dados:\n" + e.getMessage(),
                "Erro", JOptionPane.ERROR_MESSAGE);
    }

